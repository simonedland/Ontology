"""Generate reference docs from the code so they can never drift.

* docs/vocabulary.md                 entirely, from tgo/ontology.py
* docs/configuration.md              the block between the GENERATED markers, from tgo/config.py

    python scripts/gen_docs.py            # rewrite both
    python scripts/gen_docs.py --check    # exit 1 if either is out of date (used by tests)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tgo import ontology as O  # noqa: E402

OUT = ROOT / "docs" / "vocabulary.md"
CONFIG_DOC = ROOT / "docs" / "configuration.md"
BEGIN, END = "<!-- BEGIN GENERATED: config reference -->", "<!-- END GENERATED: config reference -->"


def _cell(s) -> str:
    return str(s or "").replace("|", "\\|").replace("\n", " ")


def render() -> str:
    lines = [
        "# Vocabulary reference",
        "",
        "<!-- Generated by scripts/gen_docs.py from tgo/ontology.py. Do not edit by hand. -->",
        "",
        "Every node label and relationship type the pipeline may write. Edit the vocabulary in `tgo/ontology.py`,",
        "then run `python scripts/gen_docs.py`. `tests/test_docs.py` fails if this page is stale.",
        "",
        "Namespace: `tg:` = `https://{TGO_DOMAIN}/ontology/tg#`, instances `tgr:` = `https://{TGO_DOMAIN}/id/`",
        "(`TGO_DOMAIN` defaults to `tgo.example.org`).",
        "",
        "## Epistemic status",
        "",
        "| Value | Meaning |",
        "|---|---|",
    ]
    status_doc = {
        "observed": "platform metadata, EXIF as read, OCR text as read",
        "file_declared": "XMP, docProps, ID3: forgeable by the file author",
        "inferred": "every ML output and every person link",
        "analyst": "human judgement or case grouping",
    }
    lines += [f"| `{s.value}` | {status_doc.get(s.value, '')} |" for s in O.Status]
    lines += ["", "## Field visibility (`tg:FieldVisibility`)", "", ", ".join(f"`{v.value}`" for v in O.Visibility),
              "", "## Visibility scope (`tg:visibilityScope`)", "", ", ".join(f"`{v.value}`" for v in O.Scope)
              + f" (elevated sensitivity: {', '.join(f'`{s}`' for s in sorted(O.ELEVATED_SCOPES))})", ""]

    lines += ["## Classes", ""]
    layers: dict[str, list] = {}
    for c in O.CLASSES.values():
        layers.setdefault(c.layer, []).append(c)
    for layer in ["Core", "Content", "Network", "Economy", "Derived", "Provenance"] + sorted(
            set(layers) - {"Core", "Content", "Network", "Economy", "Derived", "Provenance"}):
        if layer not in layers:
            continue
        lines += [f"### {layer}", "", "| Class | Parents | Aligned with | Status | Viewer family | Notes |",
                  "|---|---|---|---|---|---|"]
        for c in layers[layer]:
            lines.append(f"| `{c.name}` | {', '.join(f'`{p}`' for p in c.parents)} | "
                         f"{', '.join(f'`{a}`' for a in c.align)} | {c.epistemic} | {c.family} | {_cell(c.doc)} |")
        lines.append("")

    lines += ["## Relationship types", "",
              "Tiers: `structural` (container facts), `pairwise` (visible between two parties), `viewer_only`",
              "(only the collector sees it), `admin_only` (only admins see it), `derived` (computed), `provenance`.",
              ""]
    tiers: dict[str, list] = {}
    for r in O.RELATIONS.values():
        tiers.setdefault(r.tier, []).append(r)
    for tier in sorted(tiers):
        lines += [f"### {tier}", "", "| Type | Default status | FtM | RDF | Notes |", "|---|---|---|---|---|"]
        for r in tiers[tier]:
            lines.append(f"| `{r.name}` | {r.status} | {_cell(r.ftm)} | {_cell(r.rdf)} | {_cell(r.doc)} |")
        lines.append("")

    lines += ["## Forbidden (the validator fails the graph if these appear)", "",
              "Relations: " + ", ".join(f"`{x}`" for x in sorted(O.FORBIDDEN_RELATIONS)), "",
              "Labels: " + ", ".join(f"`{x}`" for x in sorted(O.FORBIDDEN_LABELS)), "",
              "## Concept schemes", "",
              "- **Group roles:** " + ", ".join(f"`{x}`" for x in O.GROUP_ROLES),
              "- **Group kinds:** " + ", ".join(f"`{x}`" for x in O.GROUP_KINDS),
              "- **Algorithms:** " + ", ".join(f"`{x}`" for x in O.ALGORITHMS),
              "- **Judgements:** " + ", ".join(f"`{x}`" for x in O.JUDGEMENTS),
              "- **Special-category chat topics (GDPR Art. 9):** " + ", ".join(
                  f"`{x}`" for x in sorted(O.SPECIAL_CATEGORY_TOPICS)),
              "", "## Not obtainable from Telegram (shown as typed gaps)", "", "| Fact | Why |", "|---|---|"]
    lines += [f"| {_cell(a)} | {_cell(b)} |" for a, b in O.NOT_OBTAINABLE]
    return "\n".join(lines) + "\n"


def render_config() -> str:
    """Tables for every Config section: key, default, meaning (from the field's inline comment)."""
    import inspect
    import re
    from dataclasses import fields

    from tgo import config as C

    comments, cls_name = {}, None
    for line in Path(C.__file__).read_text(encoding="utf-8").splitlines():
        m = re.match(r"class (\w+)", line)
        if m:
            cls_name = m.group(1)
        m = re.match(r"\s+(\w+): [^=]+=.*?#\s*(.+)$", line)
        if m and cls_name:
            comments[(cls_name, m.group(1))] = m.group(2).strip()
    cfg = C.Config()
    out = []
    for sec in fields(C.Config):
        obj = getattr(cfg, sec.name)
        doc = (inspect.getdoc(type(obj)) or "").splitlines()[0].replace("``", "`")
        out += [f"### `{sec.name}`", "", doc, "", "| Key | Default | Meaning |", "|---|---|---|"]
        tables = []
        for f in fields(obj):
            v = getattr(obj, f.name)
            default = "see table below" if isinstance(v, dict) else f"`{json.dumps(v)}`"
            out.append(f"| `{sec.name}.{f.name}` | {default} | "
                       f"{_cell(comments.get((type(obj).__name__, f.name), ''))} |")
            if isinstance(v, dict):
                tables += ["", f"`{sec.name}.{f.name}` defaults (a partial override merges into these):", "",
                           "| Entry | Value |", "|---|---|"] + [f"| `{k}` | {w} |" for k, w in v.items()]
        out += tables + [""]
    out += ["### Environment variables", "", "| Variable | Meaning |", "|---|---|"]
    out += [f"| `{k}` | {_cell(v)} |" for k, v in C.ENVIRONMENT.items()]
    return "\n".join(out)


def _splice(doc: str, block: str) -> str:
    a, b = doc.index(BEGIN) + len(BEGIN), doc.index(END)
    return doc[:a] + "\n" + block + "\n" + doc[b:]


def main(argv: list[str]) -> int:
    targets = {OUT: render()}
    if CONFIG_DOC.exists() and BEGIN in CONFIG_DOC.read_text(encoding="utf-8"):
        targets[CONFIG_DOC] = _splice(CONFIG_DOC.read_text(encoding="utf-8"), render_config())
    stale = [p for p, t in targets.items() if (p.read_text(encoding="utf-8") if p.exists() else "") != t]
    if "--check" in argv:
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date: run python scripts/gen_docs.py")
        return 1 if stale else 0
    for p in stale:
        p.write_text(targets[p], encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
