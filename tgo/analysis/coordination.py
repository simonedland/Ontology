"""Coordination detection: the CooRTweet "shared object within a time window" abstraction.

    object_id  = what is shared (normalized text hash, SimHash bucket, original
                 forwarded message, canonical URL, media file / fingerprint)
    account_id = the posting actor (channel for channel posts, sender otherwise)
    content_id = the message key
    timestamp  = message date

``detect_groups(shares, time_window, min_participation)`` returns account
pairs that shared >= ``min_participation`` distinct objects within the window
(loops removed).  Pairs become inferred edges (IDENTICAL_POST, SYNC_POST,
NEAR_DUP_POST, CO_FORWARD, CO_URL, CO_FINGERPRINT) and connected components of
>= 3 accounts become CoordinationCluster nodes, all generated by a logged
DetectionRun with its parameters.
"""
from __future__ import annotations

import hashlib
import math
import re
from collections import defaultdict
from dataclasses import dataclass
from itertools import combinations

from .. import keys as K
from ..graph import Graph
from .aggregate import chat_of, sender_of


@dataclass(frozen=True)
class Share:
    object_id: str
    kind: str          # text | simhash | forward | url | media
    account_id: str
    content_id: str
    ts: int


def normalize(text: str) -> str:
    t = re.sub(r"https?://\S+", " ", text.lower())
    t = re.sub(r"[^\w\s]", " ", t)
    return re.sub(r"\s+", " ", t).strip()


def simhash(text: str, bits: int = 64) -> int:
    toks = normalize(text).split()
    grams = [" ".join(toks[i:i + 3]) for i in range(max(1, len(toks) - 2))]
    v = [0] * bits
    for gram in grams:
        h = int(hashlib.blake2b(gram.encode(), digest_size=8).hexdigest(), 16)
        for i in range(bits):
            v[i] += 1 if (h >> i) & 1 else -1
    return sum(1 << i for i in range(bits) if v[i] > 0)


def build_shares(g: Graph, min_text_len: int = 40) -> list[Share]:
    shares: list[Share] = []
    for m in g.by_label("Message"):
        if "ServiceMessage" in m.labels or m.props.get("date") is None:
            continue
        chat = chat_of(g, m.key)
        if chat is None:
            continue
        actor = chat if chat.startswith("channel:") and "Channel" in g.nodes[chat].labels else sender_of(g, m.key)
        if actor is None:
            continue
        t = int(m.props["date"])
        text = m.props.get("text") or ""
        if len(normalize(text)) >= min_text_len:
            shares.append(Share("text:" + hashlib.sha1(normalize(text).encode()).hexdigest()[:16], "text", actor, m.key, t))
            shares.append(Share(f"simhash:{simhash(text):016x}", "simhash", actor, m.key, t))
        for e in g.out_edges(m.key, "FORWARD_OF"):
            shares.append(Share("fwd:" + e.dst, "forward", actor, m.key, t))
        for e in g.out_edges(m.key, "CONTAINS_IDENTIFIER"):
            if "Url" in g.nodes[e.dst].labels:
                shares.append(Share(e.dst, "url", actor, m.key, t))
        for e in g.out_edges(m.key, "HAS_MEDIA"):
            shares.append(Share(e.dst, "media", actor, m.key, t))
            for fp in g.in_edges(e.dst, "FINGERPRINT_OF"):
                shares.append(Share(fp.src, "media", actor, m.key, t))
    return shares


def _windowed_pairs(sorted_shares: list[Share], window: int):
    """Pairs (a, b) with 0 <= b.ts - a.ts <= window, in O(n * k) instead of O(n^2)."""
    j0 = 0
    for j, b in enumerate(sorted_shares):
        while sorted_shares[j0].ts < b.ts - window:
            j0 += 1
        for a in sorted_shares[j0:j]:
            yield a, b


def poisson_sf(k: int, lam: float) -> float:
    """P(X >= k) for X ~ Poisson(lam)."""
    if k <= 0:
        return 1.0
    term = cdf = math.exp(-lam)
    for i in range(1, k):
        term *= lam / i
        cdf += term
    return max(0.0, 1.0 - cdf)


def detect_groups(shares: list[Share], time_window: int = 60, min_participation: int = 2,
                  simhash_max_dist: int = 3, max_p: float | None = 1e-3) -> dict[tuple[str, str], dict]:
    """CooRTweet pairs plus a null model (TGO addition).

    Plain CooRTweet keeps every pair with >= min_participation co-shares, which on real
    traffic flags accounts that merely post popular URLs/domains a lot.  For each pair we
    compute the expected number of chance co-shares if both posted their own objects
    uniformly over the observed span, E = sum_o n_a(o) * n_b(o) * 2w / T, and keep the pair
    only if P(Poisson(E) >= observed) <= max_p.
    """
    by_obj: dict[str, list[Share]] = defaultdict(list)
    for s in shares:
        if s.kind != "simhash":
            by_obj[s.object_id].append(s)
    # SimHash near-duplicates: merge buckets within Hamming distance into one object
    sims = sorted((s for s in shares if s.kind == "simhash"), key=lambda s: s.ts)
    for a, b in _windowed_pairs(sims, time_window):
        if a.account_id == b.account_id:
            continue
        ha, hb = int(a.object_id[8:], 16), int(b.object_id[8:], 16)
        d = bin(ha ^ hb).count("1")
        if 0 < d <= simhash_max_dist:
            obj = f"neardup:{min(a.object_id, b.object_id)}"
            by_obj[obj] += [x for x in (a, b) if x not in by_obj[obj]]

    pairs: dict[tuple[str, str], dict] = {}
    for obj, ss in by_obj.items():
        ss.sort(key=lambda s: s.ts)
        for a, b in _windowed_pairs(ss, time_window):
            if a.account_id == b.account_id:          # remove_loops
                continue
            dt = b.ts - a.ts
            key = tuple(sorted((a.account_id, b.account_id)))
            p = pairs.setdefault(key, {"objects": defaultdict(set), "evidence": set(), "min_dt": dt,
                                       "t_first": min(a.ts, b.ts), "t_last": max(a.ts, b.ts)})
            p["objects"][a.kind if not obj.startswith("neardup:") else "neardup"].add(obj)
            p["evidence"].update((a.content_id, b.content_id))
            p["min_dt"] = min(p["min_dt"], dt)
            p["t_first"] = min(p["t_first"], a.ts)
            p["t_last"] = max(p["t_last"], b.ts)
    kept = {k: v for k, v in pairs.items() if sum(len(o) for o in v["objects"].values()) >= min_participation}
    if max_p is None or not kept:
        return kept
    span = max(1, max(s.ts for s in shares) - min(s.ts for s in shares))
    cnt: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for obj, ss in by_obj.items():
        for x in ss:
            cnt[x.account_id][obj] += 1
    out = {}
    for (a, b), v in kept.items():
        ca, cb = cnt[a], cnt[b]
        small, big = (ca, cb) if len(ca) <= len(cb) else (cb, ca)
        lam = sum(n * big[o] for o, n in small.items() if o in big) * 2 * time_window / span
        observed = sum(len(o) for o in v["objects"].values())
        p = poisson_sf(observed, lam)
        if p <= max_p:
            v["expected"], v["pValue"] = lam, p
            out[(a, b)] = v
    return out


EDGE_FOR_KIND = {"text": "IDENTICAL_POST", "neardup": "NEAR_DUP_POST", "forward": "CO_FORWARD",
                 "url": "CO_URL", "media": "CO_FINGERPRINT"}


def run(g: Graph, time_window: int = 60, min_participation: int = 2, sync_seconds: int = 5,
        max_p: float | None = 1e-3) -> dict:
    params = dict(time_window=time_window, min_participation=min_participation, sync_seconds=sync_seconds,
                  object_types=sorted(EDGE_FOR_KIND), null_model="poisson", max_p=max_p)
    shares = build_shares(g)
    pairs = detect_groups(shares, time_window, min_participation, max_p=max_p)
    out = {"shares": len(shares), "pairs": len(pairs), "clusters": 0}
    with g.activity("DetectionRun", f"coortweet:w{time_window}:m{min_participation}", agent={
            "tool": "tgo-coortweet", "version": "0.1 (port of CooRTweet detect_groups)", "codeLicense": "MIT",
            "weightsLicense": "n/a"}, algorithm="coortweet", **params) as run_key:
        adj: dict[str, set[str]] = defaultdict(set)
        for (a, b), p in pairs.items():
            total = sum(len(o) for o in p["objects"].values())
            for kind, objs in p["objects"].items():
                conf = round(min(0.95, 0.45 + 0.1 * len(objs) + 0.05 * total), 3)
                g.edge(EDGE_FOR_KIND[kind], a, b, conf=conf, method="coortweet", evidence=sorted(p["evidence"]),
                       sharedObjects=len(objs), minDeltaSec=p["min_dt"], t=p["t_first"],
                       expectedByChance=round(p.get("expected", 0.0), 4), pValue=float(f"{p.get('pValue', 0.0):.3g}"))
                g.edges[f"{a}-[{EDGE_FOR_KIND[kind]}]->{b}"].props["t_last"] = p["t_last"]
            if p["min_dt"] <= sync_seconds and "text" in p["objects"]:
                g.edge("SYNC_POST", a, b, conf=0.9, method="coortweet+sync", evidence=sorted(p["evidence"])[:20],
                       minDeltaSec=p["min_dt"], t=p["t_first"])
            adj[a].add(b)
            adj[b].add(a)
        seen: set[str] = set()
        for start in sorted(adj):
            if start in seen:
                continue
            comp, stack = set(), [start]
            while stack:
                x = stack.pop()
                if x in comp:
                    continue
                comp.add(x)
                stack.extend(adj[x] - comp)
            seen |= comp
            if len(comp) < 3:
                continue
            members = sorted(comp)
            ck = f"cluster:coord:{K.shortuuid(*members)}"
            density = sum(len(adj[m] & comp) for m in members) / (len(members) * (len(members) - 1))
            g.node(ck, "CoordinationCluster", label=f"Coordination cluster ({len(members)})", size=len(members),
                   algorithm="coortweet", density=round(density, 3), qualityScore=round(density, 3),
                   groupKind="coordination_cluster", members=members)
            g.edge("GENERATED_BY", ck, run_key)
            for m in members:
                share = len(adj[m] & comp) / (len(members) - 1)
                g.edge("IN_CLUSTER", m, ck, conf=round(0.5 + 0.45 * share, 3), method="coortweet",
                       evidence=sorted({e for (a, b), p in pairs.items() if m in (a, b) for e in p["evidence"]})[:10],
                       membershipScore=round(share, 3), role="core" if share >= 0.5 else "peripheral")
            out["clusters"] += 1

        # SAME_CREATION_DATE: >= 3 channels created on the same day (DFRLab Moldova pattern)
        by_day: dict[int, list[str]] = defaultdict(list)
        for n in g.by_label("Chat"):
            if n.props.get("createdAt"):
                by_day[int(n.props["createdAt"]) // 86400].append(n.key)
        for day, chats in by_day.items():
            if 3 <= len(chats) <= 50:
                chats.sort()
                for a, b in combinations(chats, 2):
                    g.edge("SAME_CREATION_DATE", a, b, conf=0.4, method="createdAt day bucket",
                           evidence=[a, b], day=day * 86400, t=day * 86400)
    return out
